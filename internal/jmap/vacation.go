// vacationScript is the managed script's name; the object lives in its header.
const vacationScript = jmapcore.CapVacation

const (
	vacationHeader      = "/* Generated by yarilo JMAP - DO NOT EDIT\r\n\r\n"
	vacationHeaderEnd   = "\r\n\r\n*/\r\n\r\n"
	vacationDefaultText = "I'm away at the moment.  I'll read your message and get back to you as soon as I can."
	vacationNoInclude   = "Can not enable the vacation response because the active Sieve script does not include the '" +
		vacationScript + "' script."
)

var utcDate = regexp.MustCompile(`^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d(\.\d+)?Z$`)

func (s *Server) vacationRegistry(lazy *lazyStore, accountID string) jmapcore.Registry {
	bind := func(fn func(context.Context, *userHandle, string, json.RawMessage) (any, *jmapcore.MethodError)) jmapcore.MethodEntry {
		return jmapcore.MethodEntry{Capability: jmapcore.CapVacation, Fn: func(ctx context.Context, args json.RawMessage) (any, *jmapcore.MethodError) {
			return s.withStore(lazy, accountID, func(h *userHandle) (any, *jmapcore.MethodError) {
				return fn(ctx, h, accountID, args)
			})
		}}
	}
	return jmapcore.Registry{
		"VacationResponse/get": bind(s.vacationGet),
		"VacationResponse/set": bind(s.vacationSet),
	}
}

// vacationView is the account's scripts and what they say about vacation.
type vacationView struct {
	v   sieveView
	obj jmapcore.VacationResponse
	// included reports the active script including the managed one at its top level.
	included bool
}

func (s *Server) vacationRead(ctx context.Context, h *userHandle, user string) (vacationView, error) {
	v, err := s.sieveRead(ctx, h, user)
	if err != nil {
		return vacationView{}, err
	}
	vv := vacationView{v: v, obj: defaultVacation()}
	if id, ok := v.ix.IDs[vacationScript]; ok {
		if obj, ok := parseVacationScript(v.src[id]); ok {
			vv.obj = obj
		}
	}
	if v.active != "" && v.active != vacationScript {
		vv.included = includesScript(v.src[v.ix.IDs[v.active]], vacationScript)
	}
	// Enabled only when it runs: the script active, or included by the active one.
	vv.obj.IsEnabled = vv.obj.IsEnabled && (v.active == vacationScript || vv.included)
	return vv, nil
}

// defaultVacation is the response never set: disabled, with null bodies, which
// RFC 8621 §8 answers with a default message when it is sent.
func defaultVacation() jmapcore.VacationResponse {
	return jmapcore.VacationResponse{ID: jmapcore.VacationID}
}

// parseVacationScript reads the object from the managed script's header; a
// script without a readable one is no vacation response.
func parseVacationScript(src []byte) (jmapcore.VacationResponse, bool) {
	i := bytes.Index(src, []byte(vacationHeader))
	if i < 0 {
		return jmapcore.VacationResponse{}, false
	}
	var obj jmapcore.VacationResponse
	if err := json.NewDecoder(bytes.NewReader(src[i+len(vacationHeader):])).Decode(&obj); err != nil {
		return jmapcore.VacationResponse{}, false
	}
	obj.ID = jmapcore.VacationID
	return obj, true
}

// includesScript says whether src includes name from the personal location at
// its top level; an include inside a test may not run.
func includesScript(src []byte, name string) bool {
	toks, err := lexer.Lex(bytes.NewReader(src), &lexer.Options{})
	if err != nil {
		return false
	}
	cmds, err := parser.Parse(lexer.NewStream(toks), &parser.Options{})
	if err != nil {
		return false
	}
	for _, c := range cmds {
		if !strings.EqualFold(c.Id, "include") {
			continue
		}
		personal, target := true, ""
		for _, a := range c.Args {
			switch a := a.(type) {
			case parser.TagArg:
				if strings.EqualFold(a.Value, "global") {
					personal = false
				}
			case parser.StringArg:
				target = a.Value
			case parser.StringListArg:
				if len(a.Value) == 1 {
					target = a.Value[0]
				}
			}
		}
		if personal && target == name {
			return true
		}
	}
	return false
}

func (s *Server) vacationGet(ctx context.Context, h *userHandle, accountID string, args json.RawMessage) (any, *jmapcore.MethodError) {
	var req jmapcore.GetRequest
	if err := json.Unmarshal(args, &req); err != nil {
		return nil, &jmapcore.MethodError{Type: jmapcore.ErrInvalidArguments, Description: err.Error()}
	}
	resolveGet(ctx, &req)
	if merr := checkAccount(req.AccountID, accountID); merr != nil {
		return nil, merr
	}
	props := propsOfGet(req)
	if unknown := jmapcore.UnknownProperties(jmapcore.VacationResponse{}, props); len(unknown) > 0 {
		return nil, jmapcore.InvalidProperties(unknown)
	}
	vv, err := s.vacationRead(ctx, h, accountID)
	if err != nil {
		return nil, storeFailure("VacationResponse/get", accountID, err)
	}
	resp := jmapcore.GetResponse[any]{AccountID: accountID, State: vv.v.state, List: []any{}, NotFound: []string{}}
	if req.IDs == nil || slices.Contains(*req.IDs, jmapcore.VacationID) {
		resp.List = append(resp.List, jmapcore.Project(vv.obj, props, nil))
	}
	if req.IDs != nil {
		for _, id := range *req.IDs {
			if id != jmapcore.VacationID {
				resp.NotFound = append(resp.NotFound, id)
			}
		}
	}
	return resp, nil
}

func (s *Server) vacationSet(ctx context.Context, h *userHandle, accountID string, args json.RawMessage) (any, *jmapcore.MethodError) {
	var req jmapcore.SetRequest
	if err := json.Unmarshal(args, &req); err != nil {
		return nil, &jmapcore.MethodError{Type: jmapcore.ErrInvalidArguments, Description: err.Error()}
	}
	resolveSet(ctx, &req)
	if merr := checkAccount(req.AccountID, accountID); merr != nil {
		return nil, merr
	}
	vv, err := s.vacationRead(ctx, h, accountID)
	if err != nil {
		return nil, storeFailure("VacationResponse/set state", accountID, err)
	}
	if req.IfInState != nil && *req.IfInState != vv.v.state {
		return nil, &jmapcore.MethodError{Type: jmapcore.ErrStateMismatch}
	}
	resp := jmapcore.NewSetResponse(accountID, vv.v.state)
	// One object exists and always does (RFC 8621 §8).
	singleton := &jmapcore.SetError{Type: jmapcore.SetErrSingleton}
	for cid := range req.Create {
		resp.NotCreated[cid] = singleton
	}
	for _, id := range req.Destroy {
		if id == jmapcore.VacationID {
			resp.NotDestroyed[id] = singleton
		} else {
			resp.NotDestroyed[id] = &jmapcore.SetError{Type: jmapcore.SetErrNotFound}
		}
	}
	for _, id := range sortedKeys(req.Update) {
		if id != jmapcore.VacationID {
			resp.NotUpdated[id] = &jmapcore.SetError{Type: jmapcore.SetErrNotFound}
			continue
		}
		if serr := s.vacationUpdate(ctx, h, accountID, &vv, req.Update[id]); serr != nil {
			resp.NotUpdated[id] = serr
			continue
		}
		resp.Updated[id] = nil
	}
	if after, err := s.opts.Sieve.Store.Index(ctx, accountID, h.info.Home); err == nil {
		resp.NewState = fmt.Sprint(after.State)
	}
	return resp, nil
}

// vacationUpdate applies a patch to the object and writes the managed script.
// Enabling never displaces a script of the user's own: it is refused instead.
func (s *Server) vacationUpdate(ctx context.Context, h *userHandle, user string, vv *vacationView, raw json.RawMessage) *jmapcore.SetError {
	var patch map[string]json.RawMessage
	if err := json.Unmarshal(raw, &patch); err != nil {
		return &jmapcore.SetError{Type: jmapcore.SetErrInvalidPatch, Description: err.Error()}
	}
	obj := vv.obj
	var bad []string
	for _, k := range sortedKeys(patch) {
		v := patch[k]
		var ok bool
		switch k {
		case "id":
			var id string
			ok = json.Unmarshal(v, &id) == nil && id == jmapcore.VacationID
		case "isEnabled":
			ok = json.Unmarshal(v, &obj.IsEnabled) == nil && string(v) != "null"
		case "fromDate":
			obj.FromDate, ok = vacationDate(v)
		case "toDate":
			obj.ToDate, ok = vacationDate(v)
		case "subject":
			obj.Subject, ok = vacationString(v)
			ok = ok && (obj.Subject == nil || !strings.ContainsFunc(*obj.Subject, func(r rune) bool { return r < 0x20 || r == 0x7f }))
		case "textBody":
			obj.TextBody, ok = vacationString(v)
		case "htmlBody":
			obj.HTMLBody, ok = vacationString(v)
		}
		if !ok {
			bad = append(bad, k)
		}
	}
	if len(bad) > 0 {
		return &jmapcore.SetError{Type: jmapcore.SetErrInvalidProps, Properties: bad}
	}
	active := vv.v.active
	if obj.IsEnabled && active != "" && active != vacationScript && !vv.included {
		return &jmapcore.SetError{Type: jmapcore.SetErrForbidden, Description: vacationNoInclude}
	}
	src := vacationSieve(obj)
	if serr := s.checkSieveContent(src); serr != nil {
		return serr
	}
	if serr := s.sieveQuota(ctx, h, user, vacationScript, len(src)); serr != nil {
		return serr
	}
	st := s.opts.Sieve.Store
	if err := st.SaveScript(ctx, user, h.info.Home, vacationScript, src); err != nil {
		return &jmapcore.SetError{Type: jmapcore.SetErrForbidden, Description: "the vacation script could not be stored"}
	}
	if obj.IsEnabled && active == "" {
		if err := st.SetActive(ctx, user, h.info.Home, vacationScript); err != nil {
			return &jmapcore.SetError{Type: jmapcore.SetErrForbidden, Description: "the vacation script could not be activated"}
		}
		vv.v.active = vacationScript
	}
	vv.obj = obj
	return nil
}

func vacationString(v json.RawMessage) (*string, bool) {
	if string(v) == "null" {
		return nil, true
	}
	var s string
	if json.Unmarshal(v, &s) != nil {
		return nil, false
	}
	return &s, true
}

// vacationDate takes a UTCDate (RFC 8620 §1.4) or null.
func vacationDate(v json.RawMessage) (*string, bool) {
	s, ok := vacationString(v)
	if !ok || s == nil {
		return nil, ok
	}
	if !utcDate.MatchString(*s) {
		return nil, false
	}
	if _, err := time.Parse(time.RFC3339Nano, *s); err != nil {
		return nil, false
	}
	return s, true
}

// vacationSieve writes the managed script: the object in its header, then the
// rule it stands for.
func vacationSieve(obj jmapcore.VacationResponse) []byte {
	var b bytes.Buffer
	b.WriteString(vacationHeader)
	js, _ := json.Marshal(obj)
	// "*/" in a string would end the comment early; \/ is the same JSON.
	b.Write(bytes.ReplaceAll(js, []byte("*/"), []byte(`*\/`)))
	b.WriteString(vacationHeaderEnd)

	dated := obj.FromDate != nil || obj.ToDate != nil
	if dated {
		b.WriteString("require [ \"vacation\", \"date\", \"relational\" ];\r\n\r\n")
	} else {
		b.WriteString("require [ \"vacation\" ];\r\n\r\n")
	}
	fmt.Fprintf(&b, "if allof (%t", obj.IsEnabled)
	if obj.FromDate != nil {
		fmt.Fprintf(&b, ",\r\n          currentdate :zone \"+0000\" :value \"ge\" \"iso8601\" %s", sieveQuoted(sieveISO8601(*obj.FromDate)))
	}
	if obj.ToDate != nil {
		fmt.Fprintf(&b, ",\r\n          currentdate :zone \"+0000\" :value \"lt\" \"iso8601\" %s", sieveQuoted(sieveISO8601(*obj.ToDate)))
	}
	b.WriteString(")\r\n{\r\n  vacation")
	if obj.Subject != nil {
		b.WriteString(" :subject " + sieveQuoted(*obj.Subject))
	}
	text := vacationDefaultText
	if obj.TextBody != nil {
		text = *obj.TextBody
	}
	if obj.HTMLBody != nil {
		if obj.TextBody == nil {
			text = htmlText(*obj.HTMLBody)
		}
		sum := sha256.Sum256([]byte(text + "\x00" + *obj.HTMLBody))
		boundary := "=_vacation_" + hex.EncodeToString(sum[:8])
		b.WriteString(" :mime text:\r\n")
		fmt.Fprintf(&b, "Content-Type: multipart/alternative; boundary=\"%s\"\r\n\r\n--%s\r\n", boundary, boundary)
		b.WriteString("Content-Type: text/plain; charset=utf-8\r\nContent-Transfer-Encoding: 8bit\r\n\r\n")
		b.WriteString(sieveMultiline(text))
		fmt.Fprintf(&b, "\r\n--%s\r\n", boundary)
		b.WriteString("Content-Type: text/html; charset=utf-8\r\nContent-Transfer-Encoding: 8bit\r\n\r\n")
		b.WriteString(sieveMultiline(*obj.HTMLBody))
		fmt.Fprintf(&b, "\r\n--%s--\r\n", boundary)
	} else {
		b.WriteString(" text:\r\n")
		b.WriteString(sieveMultiline(text))
		b.WriteString("\r\n")
	}
	b.WriteString(".\r\n;\r\n}\r\n")
	return b.Bytes()
}

// sieveISO8601 is a UTCDate in the form currentdate's "iso8601" part takes
// with :zone "+0000", so the two compare as strings.
func sieveISO8601(d string) string {
	t, _ := time.Parse(time.RFC3339Nano, d)
	return t.UTC().Format("2006-01-02T15:04:05-07:00")
}

func sieveQuoted(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// sieveMultiline is s as the body of a text: block, dot-stuffed (RFC 5228 §2.4.2).
func sieveMultiline(s string) string {
	lines := strings.Split(strings.ReplaceAll(s, "\r\n", "\n"), "\n")
	for i, l := range lines {
		if strings.HasPrefix(l, ".") {
			lines[i] = "." + l
		}
	}
	return strings.Join(lines, "\r\n")
}

func htmlText(html string) string {
	var b bytes.Buffer
	if err := buildmail.HTMLToText(strings.NewReader(html), func(p []byte) error { b.Write(p); return nil }); err != nil {
		return html
	}
	var lines []string
	for _, l := range strings.Split(b.String(), "\n") {
		if l = strings.Join(strings.Fields(l), " "); l != "" {
			lines = append(lines, l)
		}
	}
	return strings.Join(lines, "\n")
}
